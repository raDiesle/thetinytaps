const numberWords = ["ноль", "один", "два", "три", "четыре", "пять", "шесть", "семь", "восемь", "девять"];
const ONE = { m: "один", f: "одна", n: "одно" };

/** "одна утка", "две утки", "пять уток", "ноль уток" */
function countSentence(n: number, countable: Countable) {
  const item = countable as RussianCountable;
  if (n === 1) return `${ONE[item.gender]} ${item.singular}!`;
  if (n === 2) return `${item.gender === "f" ? "две" : "два"} ${item.plural}!`;
  return `${numberWords[n]} ${n >= 3 && n <= 4 ? item.plural : item.many}!`;
}

