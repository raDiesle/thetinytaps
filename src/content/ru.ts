/**
 * Russian counting needs the gender (один / одна / одно, два / две) and three forms:
 * "одна утка", "две утки" (2–4), "пять уток" (5–9 and 0).
 */
interface RussianCountable extends Countable {
  gender: "m" | "f" | "n";
  /** The form after 5–9 and 0: "уток". `plural` is the one after 2–4: "утки". */
  many: string;
}

const thing = (emoji: string, gender: RussianCountable["gender"], singular: string, plural: string, many: string, theme?: ThemeId): RussianCountable => ({
  emoji,
  gender,
  singular,
  plural,
  many,
  theme,
});

